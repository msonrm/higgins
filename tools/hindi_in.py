#!/usr/bin/env python3
"""ヒンディー語の入口 —— wakachi.py / josa.py に当たるもの。★だが仕事は 2 つだけ。

★★**ヒンディー語は分かち書きも助詞剥がしも要らない。** 空白があるので
ELIZA の `split_user_input()` がそのまま通り、後置詞（को・से・में・का）は
**分離語**なので韓国語の 조사 のように語へくっつかない。
→ ELIZA から見ると「空白区切りの言語が 1 つ増えた」だけになる。
★**出口も要らない**（日本語の tsunagi は「空白を消す」、韓国語の tsunagi_ko は
  「조사 を実現する」という仕事があったが、ヒンディー語にはどちらも無い）。

要るのは 2 つ:

1. ★★**danda `।` を `.` に写す。** 「切って独立トークンにする」ではない ——
   ここが実測で 2 段深かったところ（2026-09-03）:

     一段目: ELIZA は空白でしか語を切らず `eliza_uppercase` も U+0964 を素通しする
             ので、「नमस्ते।」は「नमस्ते」と**別のトークン**になり見出しに当たらない。
     二段目: ★**切るだけでは足りない。** ELIZA は「キーワードを含む**最初の節**だけを
             残す」（1966 年論文 page 37(c)）が、その節の切れ目は**ハードコードされた
             `,` `.` `BUT`**（`set_delimeters` にスクリプトからの入口が無い）。
             danda を独立トークンにしただけでは節が切れないので、
             ★**埋め戻しが文をまたぎ、danda ごと引用に入る**
             （実測「आपके काम मुश्किल है।」）。

   ★→ **`.` に写せば、エンジンが既に持っている仕組みにそのまま乗る。**
     `?` `!` も `eliza_uppercase` が `.` に潰しているので、同じ扱いに揃うことになる。
   ★画面に出る「打った通り」（draw_echo）は生の字なので、**danda は消えない** ——
     ここで写しているのは ELIZA に渡す側だけ。

2. ★★**nukta の合成形を分解形に寄せる**（U+0958..U+095F → 素の字 + U+093C）。
   क़ ख़ ग़ ज़ ड़ ढ़ फ़ य़ は 1 文字でも 2 文字でも書ける。
   ★**ゲームパッドの合成器が出すのは分解形**（`deva_nukta` が U+093C を足す）
   なので、そちらに寄せる —— 寄せないと、**実機で打った「ज़्यादा」だけが
   スクリプトの見出しに当たらない**（画面には同じ字が出るので目では分からない）。
   ★Unicode 的にも分解形が正規形（U+0958..095F は合成除外なので NFC でも戻らない）。

   hindi_in.py < 入力
"""

import sys
import unicodedata

# 合成形 → 分解形。★8 字だけなので表で持つ（C 版 native/hindi.c と対）。
NUKTA = {chr(c): unicodedata.normalize("NFD", chr(c)) for c in range(0x0958, 0x0960)}

# 文の切れ目。★ELIZA の delimiters_ は **{",", ".", "BUT"} 固定**（スクリプトから
#   増やす入口が無い）ので、そこへ寄せる。
DANDA = {"।": ".", "॥": "."}

# ★★**`लेकिन`（しかし）は原典の `BUT` にあたる。** 原典は BUT を節の切れ目に
#   しているので（「I AM SAD BUT MY MOTHER IS HAPPY」→ 前半だけ残って
#   「I AM SORRY TO HEAR YOU ARE SAD」）、ヒンディー語でも同じ働きをさせる。
#   ★写さないと**後半の家族語が勝って、悲しみの告白が素通りする**（実測 2026-09-03）。
# ★`पर` は入れない —— 後置詞の「〜の上に」と同じ形なので、切ると別の文が壊れる。
BUT = {"लेकिन": ",", "मगर": ","}


def hindi_in(s):
    for a, b in NUKTA.items():
        s = s.replace(a, b)
    for a, b in DANDA.items():
        s = s.replace(a, b)
    # ★語として独立しているときだけ写す（`लेकिनवाला` のような語中は触らない）
    return " ".join(BUT.get(w, w) for w in s.split())


def main():
    for line in sys.stdin:
        print(hindi_in(line.rstrip("\n")))


if __name__ == "__main__":
    main()
