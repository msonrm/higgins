/* ヒンディー語の入口 —— wakachi / josa の位置。★だが仕事は 2 つだけで、**出口が無い**。
 *
 * ★★**分かち書きも助詞剥がしも要らない。** 空白があるので ELIZA の
 *   split_user_input() がそのまま通り、後置詞（को・से・में・का）は**分離語**なので
 *   韓国語の 조사 のように語へくっつかない。
 * ★★**出口も要らない。** 日本語の tsunagi は「日本語に隣接する空白を消す」、
 *   韓国語の tsunagi_ko は「조사 を実現する」という仕事があったが、
 *   ヒンディー語にはどちらも無い（tsunagi は Devanagari を素通しする）。
 *
 * 入口の仕事:
 *   1. ★★**danda `।` を `.` に写す**（切って独立トークンにするのではない）。
 *      ELIZA は「キーワードを含む**最初の節**だけを残す」が、その切れ目は
 *      **ハードコードされた `,` `.` `BUT`**（set_delimeters にスクリプトからの入口が無い）。
 *      切るだけだと見出しには当たるが**節が切れず、埋め戻しが文をまたぐ**
 *      （実測「आपके काम मुश्किल है।」）。`.` に写せば既存の仕組みにそのまま乗る。
 *      ★画面に出る「打った通り」は生の字なので danda は消えない。
 *   2. ★★**nukta の合成形を分解形に寄せる**（U+0958..U+095F → 素の字 + U+093C）。
 *      ゲームパッドの合成器が出すのは分解形（deva_nukta が U+093C を足す）なので、
 *      寄せないと**実機で打った字だけが見出しに当たらない** —— 画面には同じ字が
 *      出るので、目では絶対に分からない形。
 *
 * ★規則の正典は tools/hindi_in.py。ここは手順だけ。
 */
